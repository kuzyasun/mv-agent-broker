// Offline acceptance of retained real adapter evidence; no CLI or inference.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const evidence = JSON.parse(readFileSync(new URL('../../docs/native-smoke/2026-09-30-zcode-bootstrap/adapter-resume.evidence.json', import.meta.url), 'utf8'));
assert.equal(evidence.adapterVersion, '0.2.0');
assert.equal(evidence.status, 'headless-and-resume-passed');
assert.equal(evidence.turns.length, 2);
assert.equal(evidence.processes.length, 2);
const [first, second] = evidence.turns;
const [process1, process2] = evidence.processes;
const marker = first.result.agent_reported.summary;
const ref = first.result.native_conversation_ref;
assert.match(ref, /^sess_/);
assert.equal(second.requestedNativeRef, ref);
assert.equal(second.result.native_conversation_ref, ref);
assert.equal(second.result.agent_reported.summary, marker);
assert.notEqual(process1.pid, process2.pid);
assert.ok(Date.parse(process1.finishedAt) <= Date.parse(process2.startedAt));
assert.ok(process1.args[process1.args.indexOf('--prompt') + 1].includes(marker));
assert.ok(!process2.args[process2.args.indexOf('--prompt') + 1].includes(marker));
assert.equal(process2.args[process2.args.indexOf('--resume') + 1], ref);
for (let i = 0; i < 2; i++) {
  const turn = evidence.turns[i]; const process = evidence.processes[i];
  assert.equal(turn.dispatchGateCalls, 1);
  assert.equal(turn.markerMatched, true);
  assert.equal(turn.result.native_outcome, 'completed');
  assert.equal(process.exitCode, 0);
  assert.equal(turn.events.filter((event) => event.type === 'native_ref_obtained').length, 1);
  assert.equal(turn.events.find((event) => event.type === 'native_ref_obtained').payload.ref, ref);
  const raw = JSON.parse(process.stdout);
  assert.equal(raw.sessionId, ref);
  assert.equal(raw.response, marker);
  assert.equal(raw.projection.status, 'idle');
  assert.equal(raw.usage.modelRequestCount, 1);
  assert.equal(turn.modelRequests.length, 1);
  assert.equal(turn.modelRequests[0].modelId, 'GLM-5.3-Flash');
  assert.equal(turn.modelRequests[0].providerId, 'account:zai-individual-coding-plan');
  assert.equal(turn.modelRequests[0].sessionId, ref);
  assert.equal(turn.modelRequests[0].attempt, 1);
  assert.equal(turn.modelRequests[0].finishReason, 'stop');
  const config = process.privateProviderConfig.config;
  assert.deepEqual(config.defaultModelSelection, { providerId: 'account:zai-individual-coding-plan', modelId: 'GLM-5.3-Flash', options: { reasoningLevel: 'low' } });
  assert.ok(config.providerConfigRules.providerRules.every((rule) => rule.config.visibility === 'hidden'));
  assert.deepEqual(config.modelConfigRules.manualProviderModelRules, []);
  assert.ok(config.modelConfigRules.providerModelRules.some((rule) => rule.modelId === 'GLM-5.3' && rule.config.enabled === false));
  assert.deepEqual(process.runtimeConfigs, [{ mcpEnabled: false, memoryEnabled: false, mode: 'plan' }]);
}
assert.equal(first.rawResultUsage.totalTokens + second.rawResultUsage.totalTokens, 36700);
console.log('PASS: adapter 0.2.0 native model, identity, resume across processes, marker, dispatch gates, config and usage.');
